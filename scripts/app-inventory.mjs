import { readdir, readFile, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';

// Source-only inventory: never read environment files, credentials, or live services.
const files = new Map();
for (const dir of ['src', 'api', 'server']) {
  for (const file of (await readdir(dir)).sort()) {
    if (/\.(js|css)$/.test(file)) files.set(`${dir}/${file}`, await readFile(`${dir}/${file}`, 'utf8'));
  }
}
const html = await readFile('index.html', 'utf8');
const entrypoints = [...html.matchAll(/(?:src|href)="\/(src\/[^"?]+)(?:\?[^"]*)?"/g)].map(m => m[1]);
const imports = text => [...text.matchAll(/import\s+(?:[^;]*?from\s+)?['"]([^'"]+)['"]|import\s*\(\s*['"]([^'"]+)['"]/g)].map(m => m[1] || m[2]);
const reachable = new Set();
function visit(file) {
  if (reachable.has(file)) return;
  reachable.add(file);
  for (const path of imports(files.get(file) || '')) if (path.startsWith('.')) visit(posix.normalize(posix.join(posix.dirname(file), path)));
}
entrypoints.forEach(visit);
const captures = (text, pattern) => [...new Set([...text.matchAll(pattern)].map(m => m[1]))].sort();
const sqlFiles = [...(await readdir('supabase')).filter(x => x.endsWith('.sql')),
  ...(await readdir('supabase/migrations')).filter(x => x.endsWith('.sql')).map(x => `migrations/${x}`)].sort();
const sql = new Map(await Promise.all(sqlFiles.map(async file => [file, await readFile(`supabase/${file}`, 'utf8')])));
const definitions = new Map();
for (const [file, text] of sql) {
  for (const match of text.matchAll(/create table(?: if not exists)? public\.(\w+)\s*\(([\s\S]*?)\n\);/gi)) definitions.set(match[1], { file, body: match[2].trim() });
}
const refs = new Map();
for (const [file, text] of files) for (const table of captures(text, /\.from\(['"]([^'"]+)['"]\)/g)) {
  if (!refs.has(table)) refs.set(table, []);
  refs.get(table).push(file);
}
let output = `MOTO ENGINEERING CLOUD - SOURCE INVENTORY\nGenerated by: npm run docs:inventory\nScope: checked-in source, not deployed schema or runtime verification.\nReachability follows index.html and static ES imports. Unloaded files may support old cached shells; do not delete solely from this report.\n.from() captures include Storage buckets as well as table names. Dynamic table names in main.js require reading its tables array. SQL declarations below are base definitions; ALTER statements in later files also apply.\n\n1. HTML LOAD ORDER (CSS + MODULES)\n${entrypoints.map((f, i) => `${i + 1}. ${f}`).join('\n')}\n\n2. FILE INVENTORY\n`;
for (const [file, text] of files) {
  const kind = file.startsWith('api/') ? 'Server endpoint' : file.startsWith('server/') ? 'Server helper' : reachable.has(file) ? 'Loaded browser source' : 'Not loaded by current shell';
  output += `\n${file} [${kind}; ${text.split('\n').length} lines]\n`;
  const fields = [
    ['Imports', imports(text)],
    ['Tables/buckets (literal references)', captures(text, /\.from\(['"]([^'"]+)['"]\)/g)],
    ['RPCs', captures(text, /\.rpc\(['"]([^'"]+)['"]/g)],
    ['Edge functions', captures(text, /functions\.invoke\(['"]([^'"]+)['"]/g)],
    ['Local/session storage keys (literal)', captures(text, /(?:localStorage|sessionStorage)\.(?:getItem|setItem|removeItem)\(['"]([^'"]+)['"]/g)],
    ['Declared storage-key constants', captures(text, /(?:STORAGE_KEY|STORE|[a-zA-Z]*Key)\s*=\s*['"]([^'"]+)['"]/g)],
    ['Events emitted', captures(text, /new CustomEvent\(['"]([^'"]+)['"]/g)],
    ['Events observed', captures(text, /addEventListener\(['"]([^'"]+)['"]/g)],
    ['Environment variable names', captures(text, /(?:process\.env\.|import\.meta\.env\.)([A-Z][A-Z0-9_]*)/g)]
  ];
  for (const [label, values] of fields) if (values.length) output += `  ${label}: ${values.join(', ')}\n`;
  if (text.includes('MutationObserver')) output += '  Uses MutationObserver; native port should use explicit observable state.\n';
}
output += '\n3. TABLE/BUCKET REFERENCES AND SCHEMA COVERAGE\n';
for (const [table, callers] of [...refs].sort(([a], [b]) => a.localeCompare(b))) output += `\n${table}: ${definitions.has(table) ? 'base CREATE TABLE in supabase/' + definitions.get(table).file : 'NO BASE TABLE DECLARATION FOUND (may be storage bucket or deployed-only object)'}\n  Callers: ${callers.join(', ')}\n`;
output += '\n4. CHECKED-IN BASE TABLE DEFINITIONS (NOT A COMPLETE CURRENT SCHEMA)\n';
for (const [table, { file, body }] of [...definitions].sort(([a], [b]) => a.localeCompare(b))) output += `\n${table} -- supabase/${file}\n${body}\n`;
output += '\n5. SQL FILES AND MODIFICATIONS\n';
for (const [file, text] of sql) output += `\nsupabase/${file}\n  ALTER TABLE targets: ${captures(text, /alter table (?:if exists )?(?:public\.)?(\w+)/gi).join(', ') || 'none'}\n  Functions: ${captures(text, /create (?:or replace )?function (?:public\.)?(\w+)/gi).join(', ') || 'none'}\n`;
await writeFile('docs/APP_INVENTORY.txt', output);
console.log(`Wrote docs/APP_INVENTORY.txt: ${files.size} source files, ${definitions.size} base table definitions.`);
